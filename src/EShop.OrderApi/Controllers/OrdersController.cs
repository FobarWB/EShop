using EShop.Data.Entities;
using EShop.OrderApi.Accounts;
using EShop.OrderApi.Dtos;
using EShop.OrderApi.Repositories;
using EShop.ServiceDefaults;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.ModelBinding;
using Microsoft.AspNetCore.RateLimiting;

namespace EShop.OrderApi.Controllers;

[ApiController]
[Route("api/orders")]
// Orders belong to the signed-in user: the user id comes from the token, never from the request.
[Authorize]
public class OrdersController : ControllerBase
{
    public const string IdempotencyKeyHeader = "Idempotency-Key";

    private readonly IOrderRepository _repository;
    private readonly IAccountDirectory _accounts;
    private readonly ILogger<OrdersController> _logger;

    public OrdersController(
        IOrderRepository repository,
        IAccountDirectory accounts,
        ILogger<OrdersController> logger
    )
    {
        _repository = repository;
        _accounts = accounts;
        _logger = logger;
    }

    private string UserId => User.GetUserId();

    // POST api/orders
    [HttpPost]
    public async Task<IActionResult> PlaceOrder(
        // Generated by the client once per checkout attempt and sent again on a retry;
        // a missing or malformed key is a 400.
        [FromHeader(Name = IdempotencyKeyHeader), BindRequired] Guid idempotencyKey,
        [FromBody] PlaceOrderRequest request,
        CancellationToken cancellationToken
    )
    {
        _logger.LogInformation(
            "Placing an order with idempotency key {IdempotencyKey}",
            idempotencyKey
        );

        var result = await _repository.PlaceOrderAsync(
            UserId,
            User.GetUserEmail(),
            idempotencyKey,
            request,
            cancellationToken
        );
        return PlaceOrderResponse(result);
    }

    // POST api/orders/guest: a visitor who is not signed in. Items come from the browser's cart; an email that already
    // has an account is asked to sign in, so an order never lands in an account its buyer cannot open.
    [HttpPost("guest")]
    [AllowAnonymous]
    [EnableRateLimiting(GuestCheckoutRateLimit.PolicyName)]
    public async Task<IActionResult> PlaceGuestOrder(
        [FromHeader(Name = IdempotencyKeyHeader), BindRequired] Guid idempotencyKey,
        [FromBody] GuestOrderRequest request,
        CancellationToken cancellationToken
    )
    {
        // The email itself is not logged: personal data.
        _logger.LogInformation(
            "Placing a guest order with idempotency key {IdempotencyKey}",
            idempotencyKey
        );

        // Keycloak stores emails in lower case; the order keeps the same form, so the account finds its orders later.
        var email = request.Email.Trim().ToLowerInvariant();

        // A retry first: after a lost response the account may exist already, and the retry must still get its order.
        var placed = await _repository.RetrieveGuestOrderAsync(
            email,
            idempotencyKey,
            cancellationToken
        );
        if (placed != null)
        {
            return CreatedAtAction(nameof(GetOrder), new { id = placed.OrderId }, placed);
        }

        if (await _accounts.AccountExistsAsync(email, cancellationToken))
        {
            return AccountExistsProblem();
        }

        var result = await _repository.PlaceGuestOrderAsync(
            email,
            idempotencyKey,
            request.Address,
            request.Items,
            cancellationToken
        );
        return PlaceOrderResponse(result);
    }

    // GET api/orders/5
    [HttpGet("{id:int}")]
    public async Task<ActionResult<OrderResponse>> GetOrder(
        int id,
        CancellationToken cancellationToken
    )
    {
        var order = await _repository.RetrieveOrderAsync(UserId, id, cancellationToken);
        return order is null ? OrderNotFound() : order;
    }

    // GET api/orders?page=1&pageSize=20: the user's orders, newest first.
    [HttpGet]
    [ProducesResponseType(400)]
    public async Task<ActionResult<PagedResponse<OrderSummaryResponse>>> GetOrders(
        [FromQuery] PageRequest paging,
        CancellationToken cancellationToken
    ) => await _repository.RetrieveOrdersAsync(UserId, paging, cancellationToken);

    // POST api/orders/5/cancel: a command, not a DELETE. The order stays as a document, and the stock comes back.
    [HttpPost("{id:int}/cancel")]
    public async Task<ActionResult<OrderResponse>> CancelOrder(
        int id,
        CancellationToken cancellationToken
    )
    {
        _logger.LogInformation("Cancelling order {OrderId}", id);

        var result = await _repository.ChangeStatusAsync(
            id,
            ownerId: UserId,
            OrderStatus.Cancelled,
            changedBy: UserId,
            cancellationToken
        );
        return result switch
        {
            ChangeOrderStatusResult.Changed => Ok(
                await _repository.RetrieveOrderAsync(UserId, id, cancellationToken)
            ),
            ChangeOrderStatusResult.NotFound => OrderNotFound(),
            ChangeOrderStatusResult.NotAllowed => Problem(
                statusCode: StatusCodes.Status409Conflict,
                title: "The order can no longer be cancelled"
            ),
            _ => throw new InvalidOperationException($"Unexpected status change result {result}."),
        };
    }

    // PUT api/orders/5/status: an admin moves any order through its lifecycle.
    // Both [Authorize] apply: signed in (class) and the admin role (here).
    [HttpPut("{id:int}/status")]
    [Authorize(Roles = EShopAuthenticationExtensions.AdminRole)]
    public async Task<IActionResult> ChangeStatus(
        int id,
        [FromBody] ChangeOrderStatusRequest request,
        CancellationToken cancellationToken
    )
    {
        // Not null: [Required] on the request, checked by [ApiController] before the action runs.
        var next = request.Status!.Value;
        _logger.LogInformation("Changing order {OrderId} to {Status}", id, next);

        var result = await _repository.ChangeStatusAsync(
            id,
            ownerId: null,
            next,
            changedBy: UserId,
            cancellationToken
        );
        return result switch
        {
            ChangeOrderStatusResult.Changed => NoContent(),
            ChangeOrderStatusResult.NotFound => OrderNotFound(),
            ChangeOrderStatusResult.NotAllowed => Problem(
                statusCode: StatusCodes.Status409Conflict,
                title: $"The order cannot change to {next}"
            ),
            _ => throw new InvalidOperationException($"Unexpected status change result {result}."),
        };
    }

    private IActionResult PlaceOrderResponse(PlaceOrderResult result) =>
        result switch
        {
            // A retry gets the same answer as the first attempt: 201 with the same order.
            {
                Status: PlaceOrderStatus.Placed or PlaceOrderStatus.AlreadyPlaced,
                Order: { } order,
            } => CreatedAtAction(nameof(GetOrder), new { id = order.OrderId }, order),
            { Status: PlaceOrderStatus.CartEmpty } => Problem(
                statusCode: StatusCodes.Status400BadRequest,
                title: "The cart is empty"
            ),
            { Status: PlaceOrderStatus.ProductsUnavailable, ProductIds: { } productIds } =>
                ProductsProblem("Some products are no longer available", productIds),
            { Status: PlaceOrderStatus.InsufficientStock, ProductIds: { } productIds } =>
                ProductsProblem("Not enough units in stock", productIds),
            { Status: PlaceOrderStatus.IdempotencyKeyReused } => Problem(
                statusCode: StatusCodes.Status409Conflict,
                title: "The idempotency key belongs to another order"
            ),
            _ => throw new InvalidOperationException($"Unexpected order result {result.Status}."),
        };

    // 409 with a code: the client tells it from a stock conflict (which has productIds) and offers the sign-in.
    private ObjectResult AccountExistsProblem()
    {
        var result = Problem(
            statusCode: StatusCodes.Status409Conflict,
            title: "An account with this email already exists. Please sign in."
        );
        if (result.Value is ProblemDetails problem)
        {
            problem.Extensions["code"] = "account-exists";
        }
        return result;
    }

    // Another user's order is a 404 too: the response does not reveal that it exists.
    private ObjectResult OrderNotFound() =>
        Problem(statusCode: StatusCodes.Status404NotFound, title: "Order not found");

    // 409 with the ids of the cart items to fix, so the client can mark them.
    private ObjectResult ProductsProblem(string title, IReadOnlyList<int> productIds)
    {
        var result = Problem(statusCode: StatusCodes.Status409Conflict, title: title);
        if (result.Value is ProblemDetails problem)
        {
            problem.Extensions["productIds"] = productIds;
        }
        return result;
    }
}
